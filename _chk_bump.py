from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(channel='chrome', args=['--use-gl=angle'])
    pg = b.new_page(viewport={'width':1280,'height':720})
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8765/index.html')
    pg.wait_for_timeout(2500)
    pg.evaluate("localStorage.setItem('scgp_tuto','1')")
    pg.mouse.click(640, 400)
    pg.wait_for_timeout(900)
    pg.evaluate("[...document.getElementById('circStrip').children].find(c=>c.textContent.includes('NEON'))?.click()")
    pg.wait_for_timeout(400)
    pg.evaluate("document.getElementById('playBtn').click()")
    pg.wait_for_timeout(4200)
    pg.keyboard.down('ArrowUp')
    pg.wait_for_timeout(3000)
    d1 = pg.evaluate("JSON.stringify({bump:car.bump,rough:car.rough,y:carGrp.position.y})")
    pg.keyboard.down('ArrowLeft')
    pg.wait_for_timeout(1500)
    d2 = pg.evaluate("JSON.stringify({bump:car.bump,rough:car.rough,y:carGrp.position.y,kick:car.bumpKick})")
    pg.keyboard.up('ArrowUp'); pg.keyboard.up('ArrowLeft')
    # forzar salida a la grava
    pg.evaluate("car.x += 30; car.z += 30")
    pg.keyboard.down('ArrowUp')
    pg.wait_for_timeout(1200)
    d3 = pg.evaluate("JSON.stringify({bump:car.bump,rough:car.rough,off:offroad})")
    pg.keyboard.up('ArrowUp')
    print('pista:', d1)
    print('piano:', d2)
    print('grava:', d3)
    print('errors:', errs)
    b.close()
